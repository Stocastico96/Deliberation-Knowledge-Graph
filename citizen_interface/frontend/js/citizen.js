async function loadStats() {
    try {
        const response = await fetch(`${API_BASE}/stats`);
        const data = await response.json();
        document.getElementById('stats').innerHTML = `
            <div class="stat-card"><div class="stat-number">${fmtNum(data.total_processes)}</div><div class="stat-label">Deliberation Processes</div></div>
            <div class="stat-card"><div class="stat-number">${fmtNum(data.total_contributions)}</div><div class="stat-label">Contributions</div></div>
            <div class="stat-card"><div class="stat-number">${fmtNum(data.total_fallacies)}</div><div class="stat-label">Detected Fallacies</div></div>
            <div class="stat-card"><div class="stat-number">${data.platforms ? data.platforms.length : 0}</div><div class="stat-label">Platforms</div></div>`;

        if (data.platforms && Array.isArray(data.platforms)) {
            const platformFilter = document.getElementById('platformFilter');
            platformFilter.innerHTML = '<option value="">All Platforms</option>';
            data.platforms.filter(p => p && typeof p === 'string' && p.trim().length > 0).sort().forEach(platform => {
                const option = document.createElement('option');
                option.value = platform; option.textContent = platform;
                platformFilter.appendChild(option);
            });
        }
        searchFacets = data.search_facets || {};
        populateFacetSelect('languageFilter', searchFacets.languages, { en: 'English', it: 'Italian', es: 'Spanish', ca: 'Catalan', de: 'German', fr: 'French' });
        populateFacetSelect('documentFilter', searchFacets.documents);
    } catch (error) {
        console.error('Error loading stats:', error);
        document.getElementById('stats').innerHTML = `
            <div class="stat-card" style="grid-column: 1 / -1;"><div class="stat-label" style="color: var(--error-color);">
                <i class="fas fa-exclamation-triangle"></i> Unable to load statistics. Please refresh the page.</div></div>`;
    }
}

function populateFacetSelect(id, facet, labels) {
    const el = document.getElementById(id);
    if (!el || !facet) return;
    const current = el.value;
    el.innerHTML = '<option value="">Any</option>';
    Object.entries(facet).sort((a, b) => b[1] - a[1]).forEach(([value, count]) => {
        const o = document.createElement('option');
        o.value = value;
        o.textContent = `${(labels && labels[value]) || truncate(value, 60)} (${fmtNum(count)})`;
        el.appendChild(o);
    });
    if (current) el.value = current;
}

