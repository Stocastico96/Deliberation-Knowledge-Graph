function bindResultCards(container) {
    container.querySelectorAll('.result-card[data-uri]:not([data-item])').forEach(card => {
        card.addEventListener('click', () => viewProcess(card.dataset.uri));
        card.addEventListener('keydown', (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); viewProcess(card.dataset.uri); } });
    });
}

function bindInspectButtons(container) {
    container.querySelectorAll('[data-inspect]').forEach(b => b.addEventListener('click', (e) => { e.stopPropagation(); showResourceDetails(b.dataset.inspect); }));
    container.querySelectorAll('[data-process]').forEach(b => b.addEventListener('click', (e) => { e.stopPropagation(); closeResourceModal(); viewProcess(b.dataset.process); }));
}

