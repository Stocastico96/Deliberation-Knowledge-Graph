function emptyState(title, hint) { return `<div class="empty-state"><i class="fas fa-search" style="font-size: 3rem; margin-bottom: 1rem;"></i><h3>${escapeHtml(title)}</h3><p>${escapeHtml(hint)}</p></div>`; }
function escapeHtml(text) { const div = document.createElement('div'); div.textContent = text == null ? '' : String(text); return div.innerHTML; }
function escapeAttr(text) { return escapeHtml(text).replace(/"/g, '&quot;').replace(/'/g, '&#39;'); }
function truncate(text, maxLength) { text = text == null ? '' : String(text); return text.length <= maxLength ? text : text.substr(0, maxLength) + '...'; }
function fmtNum(n) { return (n == null || isNaN(n)) ? '0' : Number(n).toLocaleString('en-US'); }
function fmtMetric(v) { const n = Number(v); return isNaN(n) ? String(v) : (Number.isInteger(n) ? String(n) : n.toFixed(3)); }
function getFallacyName(uri) { if (!uri) return 'Unknown'; const name = uri.split('#').pop().split('/').pop(); return name.replace(/_/g, ' ').replace(/([A-Z])/g, ' $1').trim(); }
function formatDate(dateString) {
    if (!dateString) return 'N/A';
    try {
        let date;
        if (dateString.includes('T')) date = new Date(dateString);
        else if (dateString.match(/^\d{4}-\d{2}-\d{2}$/)) date = new Date(dateString);
        else if (dateString.includes('/')) date = new Date(dateString.split(/[\s\/]/)[0]);
        else return dateString;
        if (isNaN(date.getTime())) return dateString;
        return date.toISOString().split('T')[0];
    } catch (e) { return dateString; }
}

