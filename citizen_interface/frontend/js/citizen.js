async function viewProcess(uri, skipUrl) {
    showLoading();
    if (!skipUrl) pushUrl({ process: uri });
    try {
        const [summaryRes, legacyRes] = await Promise.all([
            fetch(`${API_BASE}/process/summary?uri=${encodeURIComponent(uri)}`),
            fetch(`${API_BASE}/process?uri=${encodeURIComponent(uri)}`)
        ]);
        if (!summaryRes.ok) {
            const err = await summaryRes.json().catch(() => ({}));
            showError(err.error === 'Process not found' ? 'This process does not exist in the knowledge graph.' : 'Error loading process details');
            return;
        }
        const summary = await summaryRes.json();
        const legacy = legacyRes.ok ? await legacyRes.json() : {};
        currentProcess = { ...legacy, ...summary };
        displayProcessDetails(currentProcess);
    } catch (error) {
        console.error('Error loading process:', error);
        showError('Error loading process details');
    }
}

