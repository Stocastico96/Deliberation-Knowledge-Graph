function openPlatform(p) {
    if (!p) return;
    setSelectValue('platformFilter', p.name);
    if (p.processes && p.processes.length === 1) { viewProcess(p.processes[0].uri); return; }
    if (p.processes && p.processes.length > 1) {
        backToResults();
        const resultsContainer = document.getElementById('searchResults');
        resultsContainer.innerHTML = `
            <div class="notice notice-muted"><strong>${escapeHtml(p.name)}</strong> – ${escapeHtml(p.description || '')}
            ${p.url ? ` <a href="${escapeAttr(p.url)}" target="_blank" rel="noopener">Platform website <i class="fas fa-external-link-alt" aria-hidden="true"></i></a>` : ''}</div>
            ${p.processes.map(pr => `
                <div class="result-card" role="button" tabindex="0" data-uri="${escapeAttr(pr.uri)}">
                    <div class="result-header"><h3>${escapeHtml(pr.title)}</h3></div>
                    <div class="result-meta"><span><i class="fas fa-globe"></i> ${escapeHtml(p.name)}</span></div>
                </div>`).join('')}`;
        bindResultCards(resultsContainer);
        resultsContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
        return;
    }
    // many processes: run a search restricted to the platform
    const input = document.getElementById('searchInput');
    if (!input.value.trim()) input.value = p.name;
    performSearch();
}

