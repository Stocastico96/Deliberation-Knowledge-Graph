function renderServerPagination(container, total, offset, limit) {
    const totalPages = Math.ceil(total / limit);
    const currentPage = Math.floor(offset / limit) + 1;
    if (totalPages <= 1) { container.innerHTML = ''; return; }
    let html = '<nav class="pagination" aria-label="Contributions pagination">';
    const btn = (page, label, active) => `<button class="pagination-btn ${active ? 'active' : ''}" data-page="${page}" ${active ? 'aria-current="page"' : ''}>${label}</button>`;
    if (currentPage > 1) html += btn(currentPage - 1, '<i class="fas fa-chevron-left"></i> Previous');
    const maxButtons = 5;
    let startPage = Math.max(1, currentPage - Math.floor(maxButtons / 2));
    let endPage = Math.min(totalPages, startPage + maxButtons - 1);
    if (endPage - startPage < maxButtons - 1) startPage = Math.max(1, endPage - maxButtons + 1);
    if (startPage > 1) { html += btn(1, '1'); if (startPage > 2) html += '<span class="pagination-ellipsis">...</span>'; }
    for (let i = startPage; i <= endPage; i++) html += btn(i, String(i), i === currentPage);
    if (endPage < totalPages) { if (endPage < totalPages - 1) html += '<span class="pagination-ellipsis">...</span>'; html += btn(totalPages, String(totalPages)); }
    if (currentPage < totalPages) html += btn(currentPage + 1, 'Next <i class="fas fa-chevron-right"></i>');
    html += '</nav>';
    container.innerHTML = html;
    container.querySelectorAll('[data-page]').forEach(b => b.addEventListener('click', () => {
        contribState.offset = (parseInt(b.dataset.page) - 1) * contribState.limit;
        loadContributions();
        document.getElementById('contributions-section').scrollIntoView({ behavior: 'smooth', block: 'start' });
    }));
}

