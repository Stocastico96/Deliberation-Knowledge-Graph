let autocompleteTimeout;
async function handleAutocomplete() {
    clearTimeout(autocompleteTimeout);
    const query = document.getElementById('searchInput').value.trim();
    const autocompleteDiv = document.getElementById('autocomplete');
    if (query.length < 2) { autocompleteDiv.classList.remove('show'); return; }
    autocompleteTimeout = setTimeout(async () => {
        try {
            const response = await fetch(`${API_BASE}/autocomplete?q=${encodeURIComponent(query)}`);
            const data = await response.json();
            if (data.suggestions && data.suggestions.length > 0) {
                autocompleteDiv.innerHTML = data.suggestions.map(s => `<div class="autocomplete-item" role="option" tabindex="0" data-s="${escapeAttr(s)}">${escapeHtml(s)}</div>`).join('');
                autocompleteDiv.querySelectorAll('.autocomplete-item').forEach(it => {
                    it.addEventListener('click', () => selectSuggestion(it.dataset.s));
                    it.addEventListener('keydown', (e) => { if (e.key === 'Enter') selectSuggestion(it.dataset.s); });
                });
                autocompleteDiv.classList.add('show');
            } else autocompleteDiv.classList.remove('show');
        } catch (error) { console.error('Autocomplete error:', error); }
    }, 300);
}

