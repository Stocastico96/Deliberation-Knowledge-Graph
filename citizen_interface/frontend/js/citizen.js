// ---------------------------------------------------------------------------
function visualizeGraph(process) {
    const container = document.getElementById('graphViz');
    if (!container || typeof d3 === 'undefined') return;
    container.innerHTML = '';
    const nodes = [{ id: process.uri, label: truncate(process.title || 'Process', 40), type: 'process', uri: process.uri }];
    const links = [];
    const participantsMap = new Map();
    const contributionUriToId = new Map();
    (process.contributions || []).forEach((c, i) => {
        const nodeId = `contribution_${i}`;
        contributionUriToId.set(c.uri, nodeId);
        const isComment = !!c.responseTo;
        nodes.push({ id: nodeId, label: isComment ? `Reply ${i + 1}` : `Contribution ${i + 1}`, type: isComment ? 'comment' : 'contribution', uri: c.uri });
        if (!isComment) links.push({ source: process.uri, target: nodeId });
        if (c.author && c.author !== 'Unknown') participantsMap.set(c.author, nodeId);
    });
    (process.contributions || []).forEach((c) => {
        if (c.responseTo) {
            const commentId = contributionUriToId.get(c.uri);
            const parentId = contributionUriToId.get(c.responseTo);
            if (commentId && parentId) links.push({ source: parentId, target: commentId, type: 'responseTo' });
            else if (commentId) links.push({ source: process.uri, target: commentId, type: 'responseTo' });
        }
    });
    let participantIndex = 0;
    participantsMap.forEach((contributionId, participantName) => {
        const participantId = `participant_${participantIndex++}`;
        nodes.push({ id: participantId, label: participantName.length > 30 ? participantName.substr(0, 30) + '...' : participantName, type: 'participant', uri: null });
        links.push({ source: contributionId, target: participantId });
    });
    const width = Math.max(280, Math.min(container.clientWidth || 600, window.innerWidth - 32));
    const height = 500;
    const svg = d3.select('#graphViz').append('svg').attr('viewBox', `0 0 ${width} ${height}`).attr('width', '100%').attr('height', height).style('max-width', '100%').attr('role', 'img').attr('aria-label', 'Force-directed graph of the process and the contributions on this page');
    const simulation = d3.forceSimulation(nodes)
        .force('link', d3.forceLink(links).id(d => d.id).distance(90))
        .force('charge', d3.forceManyBody().strength(-250))
        .force('center', d3.forceCenter(width / 2, height / 2));
    const link = svg.append('g').selectAll('line').data(links).enter().append('line')
        .attr('stroke', d => d.type === 'responseTo' ? '#f59e0b' : '#999')
        .attr('stroke-width', d => d.type === 'responseTo' ? 2.5 : 2)
        .attr('stroke-dasharray', d => d.type === 'responseTo' ? '5,5' : '0');
    const node = svg.append('g').selectAll('circle').data(nodes).enter().append('circle')
        .attr('r', d => d.type === 'process' ? 15 : d.type === 'participant' ? 10 : 8)
        .attr('fill', d => d.type === 'process' ? '#4a9d3c' : d.type === 'participant' ? '#ffd700' : d.type === 'comment' ? '#f59e0b' : '#10b981')
        .style('cursor', 'pointer')
        .on('click', function (event, d) { event.stopPropagation(); if (d.uri) showResourceDetails(d.uri); })
        .call(d3.drag().on('start', dragstarted).on('drag', dragged).on('end', dragended));
    const label = svg.append('g').selectAll('text').data(nodes).enter().append('text').text(d => d.label).attr('font-size', 10).attr('dx', 12).attr('dy', 4);
    simulation.on('tick', () => {
        link.attr('x1', d => d.source.x).attr('y1', d => d.source.y).attr('x2', d => d.target.x).attr('y2', d => d.target.y);
        node.attr('cx', d => d.x).attr('cy', d => d.y);
        label.attr('x', d => d.x).attr('y', d => d.y);
    });
    function dragstarted(event, d) { if (!event.active) simulation.alphaTarget(0.3).restart(); d.fx = d.x; d.fy = d.y; }
    function dragged(event, d) { d.fx = event.x; d.fy = event.y; }
    function dragended(event, d) { if (!event.active) simulation.alphaTarget(0); d.fx = null; d.fy = null; }
}

