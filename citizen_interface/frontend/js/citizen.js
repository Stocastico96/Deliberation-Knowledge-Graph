// ---------------------------------------------------------------------------
async function loadContributions() {
    const grid = document.getElementById('contributions-grid');
    const pag = document.getElementById('contributions-pagination');
    if (!grid) return;
    grid.innerHTML = '<div class="loading"><div class="spinner"></div></div>';
    const params = new URLSearchParams({ uri: contribState.uri, offset: contribState.offset, limit: contribState.limit, order: contribState.order });
    if (contribState.kind) params.set('kind', contribState.kind);
    if (contribState.condition) params.set('condition', contribState.condition);
    if (contribState.topic) params.set('topic', contribState.topic);
    try {
        const response = await fetch(`${API_BASE}/process/contributions?${params.toString()}`);
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        const data = await response.json();
        contribState.total = data.total;
        const label = document.getElementById('contrib-count-label');
        const unfiltered = !contribState.kind && !contribState.condition && !contribState.topic;
        const withoutText = unfiltered && contribState.totalAll > data.total ? contribState.totalAll - data.total : 0;
        if (label) label.textContent = withoutText ? `(${fmtNum(data.total)} with text, of ${fmtNum(contribState.totalAll)})` : `(${fmtNum(data.total)})`;
        const note = document.getElementById('contrib-no-text-note');
        if (note) note.hidden = !withoutText;
        if (note && withoutText) note.textContent = `${fmtNum(withoutText)} contributions have no text in the source data (for example feedback submitted only as an attachment). They are counted in the statistics but cannot be listed.`;
        if (!data.contributions.length) {
            grid.innerHTML = '<p class="empty-state">No contributions match the current filters.</p>';
            pag.innerHTML = '';
        } else {
            grid.innerHTML = data.contributions.map(contributionCard).join('');
            bindInspectButtons(grid);
            grid.querySelectorAll('.contribution-card').forEach(card => {
                card.addEventListener('click', () => showResourceDetails(card.dataset.uri));
                card.addEventListener('keydown', (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); showResourceDetails(card.dataset.uri); } });
            });
            renderServerPagination(pag, data.total, contribState.offset, contribState.limit);
        }
        if (currentProcess) visualizeGraph({ ...currentProcess, contributions: data.contributions.map(c => ({ uri: c.uri, author: c.author ? c.author.name : 'Unknown', responseTo: c.responseTo, text: c.text })) });
    } catch (error) {
        console.error('Error loading contributions:', error);
        grid.innerHTML = '<p class="error-state"><i class="fas fa-exclamation-circle"></i> Unable to load contributions.</p>';
    }
}

