function setupEventListeners() {
    const searchBtn = document.getElementById('searchBtn');
    const searchInput = document.getElementById('searchInput');
    searchBtn.addEventListener('click', performSearch);
    searchInput.addEventListener('keypress', (e) => { if (e.key === 'Enter') performSearch(); });
    searchInput.addEventListener('input', handleAutocomplete);

    const toggle = document.getElementById('filtersToggle');
    if (toggle) {
        toggle.addEventListener('click', () => {
            const panel = document.getElementById('advancedFilters');
            const open = panel.classList.toggle('open');
            toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
        });
    }
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            const modal = document.getElementById('resourceModal');
            if (modal && modal.style.display !== 'none') closeResourceModal();
        }
    });
    window.addEventListener('popstate', () => handleDeepLinks(true));
}

function handleDeepLinks(fromHistory) {
    const params = new URLSearchParams(window.location.search);
    const processUri = params.get('process');
    const resourceUri = params.get('show_resource');
    const q = params.get('q');
    if (q && !fromHistory) {
        document.getElementById('searchInput').value = q;
        if (params.get('platform')) setSelectValue('platformFilter', params.get('platform'));
        if (params.get('mode')) setSelectValue('searchMode', params.get('mode'));
        performSearch(true);
    }
    if (processUri) viewProcess(processUri, true);
    if (resourceUri) showResourceDetails(resourceUri, true);
}

function setSelectValue(id, value) {
    const el = document.getElementById(id);
    if (!el) return;
    let found = false;
    for (const o of el.options) { if (o.value === value) { found = true; break; } }
    if (!found) { const o = document.createElement('option'); o.value = value; o.textContent = value; el.appendChild(o); }
    el.value = value;
}

function pushUrl(params) {
    const url = new URL(window.location.href);
    url.search = '';
    Object.entries(params).forEach(([k, v]) => { if (v) url.searchParams.set(k, v); });
    window.history.pushState({}, document.title, url.toString());
}

