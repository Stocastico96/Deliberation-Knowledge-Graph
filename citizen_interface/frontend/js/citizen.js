function renderParticipantsPagination(totalParticipants, currentPage) {
    const paginationContainer = document.getElementById('participants-pagination');
    if (!paginationContainer) return;
    const totalPages = Math.ceil(totalParticipants / PARTICIPANTS_PER_PAGE);
    if (totalPages <= 1) { paginationContainer.innerHTML = ''; return; }
    let html = '<div class="pagination">';
    if (currentPage > 1) html += `<button class="pagination-btn" onclick="changeParticipantsPage(${currentPage - 1})"><i class="fas fa-chevron-left"></i> Previous</button>`;
    const maxButtons = 5;
    let startPage = Math.max(1, currentPage - Math.floor(maxButtons / 2));
    let endPage = Math.min(totalPages, startPage + maxButtons - 1);
    if (endPage - startPage < maxButtons - 1) startPage = Math.max(1, endPage - maxButtons + 1);
    if (startPage > 1) { html += `<button class="pagination-btn" onclick="changeParticipantsPage(1)">1</button>`; if (startPage > 2) html += '<span class="pagination-ellipsis">...</span>'; }
    for (let i = startPage; i <= endPage; i++) html += `<button class="pagination-btn ${i === currentPage ? 'active' : ''}" onclick="changeParticipantsPage(${i})">${i}</button>`;
    if (endPage < totalPages) { if (endPage < totalPages - 1) html += '<span class="pagination-ellipsis">...</span>'; html += `<button class="pagination-btn" onclick="changeParticipantsPage(${totalPages})">${totalPages}</button>`; }
    if (currentPage < totalPages) html += `<button class="pagination-btn" onclick="changeParticipantsPage(${currentPage + 1})">Next <i class="fas fa-chevron-right"></i></button>`;
    html += '</div>';
    paginationContainer.innerHTML = html;
}

